// Tuning vs held-out gap for the escalation threshold (SHI-123). No model calls: reads the stored
// real-Jev rows in results.json (tuning) and results.holdout.json (held-out) and writes evals/GAP.md.
//   node evals/gap.mjs
// Re-run after `npm run eval` so newly reviewed candidates are in the tuning rows.
import { readFileSync, writeFileSync } from "node:fs";
import { POLICY } from "../src/verdict.js";
import { MISS_COST, FALSE_COST, sweep, bestOf, escalationAt, severityRate } from "./metrics.mjs";

const load = (f) => JSON.parse(readFileSync(new URL(f, import.meta.url), "utf8"));
const tune = load("results.json"), held = load("results.holdout.json");
if (tune.summary.mock || held.summary.mock) { console.error("Mock results: gap.mjs needs real Jev rows."); process.exit(1); }
const T = tune.rows, H = held.rows;

const grid = { from: 0.1, to: 0.5, step: 0.05 };
const sT = sweep(T, grid), sH = sweep(H, grid), sAll = sweep([...T, ...H], grid);
const tuned = bestOf(sT);                                  // what re-tuning on the tuning set alone picks
const onHeld = escalationAt(H, tuned.threshold);           // ...and how that choice does on unseen data
const policyT = escalationAt(T, POLICY.escalateAt), policyH = escalationAt(H, POLICY.escalateAt);

// Sensitivity: the 10:1 miss/false-alarm ratio is an assumption, so show what other ratios would pick.
const ratios = [3, 5, 10, 20].map((m) => ({
  m, tune: bestOf(sweep(T, { ...grid, missCost: m })).threshold, held: bestOf(sweep(H, { ...grid, missCost: m })).threshold,
  all: bestOf(sweep([...T, ...H], { ...grid, missCost: m })).threshold,
}));

// Where the false alarms come from: gold "no escalation" rows that score in the 0.2-0.5 band.
const band = [...T, ...H].filter((r) => !r.gold.escalate && r.answers.escalate.noul >= POLICY.escalateAt)
  .sort((a, b) => b.answers.escalate.noul - a.answers.escalate.noul);
// And the misses: gold escalations that scored under the policy threshold.
const low = [...T, ...H].filter((r) => r.gold.escalate && r.answers.escalate.noul < POLICY.escalateAt)
  .sort((a, b) => a.answers.escalate.noul - b.answers.escalate.noul);

const f = (x, d = 2) => Number(x).toFixed(d);
const pp = (x) => `${x > 0 ? "+" : ""}${(100 * x).toFixed(0)} pts`;
const md = `# Escalation threshold: tuning vs held-out gap

Model \`${tune.summary.model}\`. Tuning set n=${T.length}${tune.summary.candidatesIncluded?.length ? ` (includes reviewed candidates ${tune.summary.candidatesIncluded.join(", ")})` : " (no reviewed candidates yet)"}, held-out n=${H.length}.
Generated by [gap.mjs](gap.mjs) from stored Jev answers, no new model calls. Cost model: miss = ${MISS_COST}x false alarm. Small samples: one update moves recall by ${f(100 / Math.max(1, T.filter((r) => r.gold.escalate).length), 0)} to ${f(100 / Math.max(1, H.filter((r) => r.gold.escalate).length), 0)} points.

## Headline
| | Tuning | Held-out | Gap (held-out minus tuning) |
|---|---|---|---|
| Recall at policy ${POLICY.escalateAt} | ${f(policyT.recall)} | ${f(policyH.recall)} | ${pp(policyH.recall - policyT.recall)} |
| Precision at policy ${POLICY.escalateAt} | ${f(policyT.precision)} | ${f(policyH.precision)} | ${pp(policyH.precision - policyT.precision)} |
| Cost at policy ${POLICY.escalateAt} (per update) | ${f(policyT.cost / T.length)} | ${f(policyH.cost / H.length)} | |
| Lowest-cost threshold on this set | ${bestOf(sT).threshold} | ${bestOf(sH).threshold} | |
| Severity-weighted error rate (health) | ${f(severityRate(T).rate)} | ${f(severityRate(H).rate)} | |

**Re-tuned on the tuning set alone:** ${tuned.threshold} (recall ${f(tuned.recall)}, precision ${f(tuned.precision)}). Applied to held-out: recall ${f(onHeld.recall)}, precision ${f(onHeld.precision)}, cost ${onHeld.cost} (held-out's own best is ${bestOf(sH).threshold} at cost ${bestOf(sH).cost}).
**Pooled (all ${T.length + H.length})** lowest cost: ${bestOf(sAll).threshold}. Pooled numbers cannot measure a gap; they only use every label for the choice.

## Sweep
| threshold | tuning P / R | tuning cost | held-out P / R | held-out cost | pooled cost |
|---|---|---|---|---|---|
${sT.map((t, i) => `| ${t.threshold}${t.threshold === POLICY.escalateAt ? " (policy)" : ""} | ${f(t.precision)} / ${f(t.recall)} | ${t.cost} | ${f(sH[i].precision)} / ${f(sH[i].recall)} | ${sH[i].cost} | ${sAll[i].cost} |`).join("\n")}

## Sensitivity to the miss/false-alarm ratio
| miss cost : false alarm | best on tuning | best on held-out | best pooled |
|---|---|---|---|
${ratios.map((r) => `| ${r.m}:1 | ${r.tune} | ${r.held} | ${r.all} |`).join("\n")}

## Where the errors sit at policy ${POLICY.escalateAt}
False escalations (gold: no exec needed), highest score first:
${band.map((r) => `- ${r.id} (${r.tax}, gold ${r.gold.health}): ${f(r.answers.escalate.noul)}`).join("\n") || "- none"}

Missed escalations (gold: exec needed), lowest score first:
${low.map((r) => `- ${r.id} (${r.tax}, claimed ${r.facts.claimed ?? "none"}): ${f(r.answers.escalate.noul)}`).join("\n") || "- none"}
`;
writeFileSync(new URL("GAP.md", import.meta.url), md);
console.log(md);
